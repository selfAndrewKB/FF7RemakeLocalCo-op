// Origin-aware copy of Square Enix's level-0 BloomReduce pixel shader (fix F1 of RE-split-bit2-leak.md).
//
// Provenance: the original DXBC was taken from RenderDoc capture Remake/Dumps/rdc/dx11-solo-taa.rdc, EID 15337
// (ps2953, SE_RCPassBloomReduce__Process level 0 via SE_BloomReduce__BindFirstExact2x, D3D11). It reads the
// source view rect from cb0[20] = (Min.x, Min.y, W, H) but used only .zw, so a view whose rect does not start
// at (0,0) (player 2) built its bloom from player 1's rows. This copy is the original, byte for byte, with four
// instructions inserted into SHEX, one before each tap's UV scale (after the mirror clamp, which stays in
// view-local space):
//     add r1.yw, r1.yyyw, cb0[20].xxxy   ; before mul r1.yw, r1.yyyw, cb0[0].zzzw   (tap 1)
//     add r1.yw, r1.yyyw, cb0[20].xxxy   ; before mul r1.yw, r1.yyyw, cb0[0].zzzw   (tap 2)
//     add r1.xz, r1.xxzx, cb0[20].xxyx   ; before mul r1.xz, r1.xxzx, cb0[0].zzwz   (tap 3)
//     add r0.yz, r0.yyzy, cb0[20].xxyx   ; before mul r0.yz, r0.yyzy, cb0[0].zzwz   (tap 4)
// SHEX length, chunk size, container size and the DXBC checksum were fixed up (binary patch, no recompile).
// Chunks: ISGN, OSGN (byte-identical to the original), SHEX. No RDEF/STAT (the original is stripped too).
// Interface (unchanged): in v0 TEXCOORD0 (xyz used), v1 SV_Position (xy); out o0 SV_Target0 float4;
// t0 Texture2D<float4>, s0 sampler, cb0[22] (reads cb0[0].zw, cb0[19].xy, cb0[20].xyzw, cb0[21].zw).
// Validation (RE-bloom-shader-patch.md): D3D11 WARP, original vs this copy bit-identical with Min = (0,0);
// with Min = (0,540) and (960,0) this copy equals the original run on the view rect moved to (0,0), bit for bit.
// Tool: patch.py (see the RE doc). Only valid for this game build's shader; identify the original by checksum.

